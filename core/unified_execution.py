class TopologyDetector:
    """
    Detect hardware topology at runtime.
    
    Detection priority:
    1. SLURM environment variables (inside job)
    2. sinfo query (on login node)
    3. System introspection (nvidia-smi, /proc/cpuinfo)
    
    NO HARDCODED VALUES - all detection is dynamic.
    """
    
    def __init__(self):
        self._cache: Dict[str, HardwareTopology] = {}
    
    def detect(self, partition: str = "") -> HardwareTopology:
        """
        Detect hardware topology for a partition.
        
        Args:
            partition: SLURM partition name (empty for current allocation)
            
        Returns:
            HardwareTopology with all values detected at runtime
        """
        cache_key = partition or "_current_"
        
        if cache_key in self._cache:
            return self._cache[cache_key]
        
        # Try detection methods in order
        topology = self._detect_from_slurm_env()
        
        if topology is None and partition:
            topology = self._detect_from_sinfo(partition)
        
        if topology is None:
            topology = self._detect_from_system()
        
        if topology is None:
            # Fallback - should not happen in production
            logger.warning("Could not detect topology, using minimal defaults")
            topology = HardwareTopology(
                partition=partition or "unknown",
                cpu_cores_per_node=os.cpu_count() or 1,
                gpus_per_node=0,
                detection_method="fallback"
            )
        
        self._cache[cache_key] = topology
        return topology
    
    def _detect_from_slurm_env(self) -> Optional[HardwareTopology]:
        """Detect from SLURM environment variables (inside job)."""
        
        if 'SLURM_JOB_ID' not in os.environ:
            return None
        
        cpus = None
        gpus = 0
        partition = os.environ.get('SLURM_JOB_PARTITION', 'unknown')
        
        # CPU detection
        if 'SLURM_CPUS_ON_NODE' in os.environ:
            cpus = int(os.environ['SLURM_CPUS_ON_NODE'])
        elif 'SLURM_JOB_CPUS_PER_NODE' in os.environ:
            val = os.environ['SLURM_JOB_CPUS_PER_NODE']
            cpus = int(val.split('(')[0])
        
        # GPU detection
        if 'SLURM_GPUS_ON_NODE' in os.environ:
            gpus = int(os.environ['SLURM_GPUS_ON_NODE'])
        elif 'SLURM_GPUS_PER_NODE' in os.environ:
            gpus = int(os.environ['SLURM_GPUS_PER_NODE'])
        elif 'CUDA_VISIBLE_DEVICES' in os.environ:
            devs = os.environ['CUDA_VISIBLE_DEVICES']
            if devs and devs.lower() not in ('', 'nodevfiles'):
                gpus = len([d for d in devs.split(',') if d.strip()])
        
        if cpus is None:
            return None
        
        gpu_vendor = GPUVendor.NVIDIA if gpus > 0 else GPUVendor.NONE
        
        logger.info(f"Detected topology from SLURM env: {cpus} CPUs, {gpus} GPUs")
        
        return HardwareTopology(
            partition=partition,
            cpu_cores_per_node=cpus,
            gpus_per_node=gpus,
            gpu_vendor=gpu_vendor,
            detection_method="slurm_env"
        )
    
    def _detect_from_sinfo(self, partition: str) -> Optional[HardwareTopology]:
        """Detect from sinfo query (on login node)."""
        
        try:
            # Query CPU count
            result = subprocess.run(
                ['sinfo', '-p', partition, '-N', '-h', '-o', '%c'],
                capture_output=True, text=True, timeout=10
            )
            if result.returncode != 0:
                return None
            
            cpus = int(result.stdout.strip().split()[0])
            
            # Query GPU count
            result = subprocess.run(
                ['sinfo', '-p', partition, '-N', '-h', '-o', '%G'],
                capture_output=True, text=True, timeout=10
            )
            
            gpus = 0
            if result.returncode == 0 and result.stdout.strip():
                gres = result.stdout.strip().split()[0]
                match = re.search(r'gpu:(?:\w+:)?(\d+)', gres)
                if match:
                    gpus = int(match.group(1))
            
            gpu_vendor = GPUVendor.NVIDIA if gpus > 0 else GPUVendor.NONE
            
            logger.info(f"Detected topology from sinfo: {cpus} CPUs, {gpus} GPUs")
            
            return HardwareTopology(
                partition=partition,
                cpu_cores_per_node=cpus,
                gpus_per_node=gpus,
                gpu_vendor=gpu_vendor,
                detection_method="sinfo"
            )
            
        except Exception as e:
            logger.debug(f"sinfo detection failed: {e}")
            return None
    
    def _detect_from_system(self) -> Optional[HardwareTopology]:
        """Detect from system introspection."""
        
        cpus = os.cpu_count() or 1
        gpus = 0
        gpu_vendor = GPUVendor.NONE
        
        # Try nvidia-smi
        try:
            result = subprocess.run(
                ['nvidia-smi', '--query-gpu=count', '--format=csv,noheader'],
                capture_output=True, text=True, timeout=5
            )
            if result.returncode == 0:
                gpus = int(result.stdout.strip().split('\n')[0])
                gpu_vendor = GPUVendor.NVIDIA
        except Exception:
            pass
        
        logger.info(f"Detected topology from system: {cpus} CPUs, {gpus} GPUs")
        
        return HardwareTopology(
            partition="local",
            cpu_cores_per_node=cpus,
            gpus_per_node=gpus,
            gpu_vendor=gpu_vendor,
            detection_method="system"
        )


# Singleton detector
_detector = None

def get_detector() -> TopologyDetector:
    """Get the singleton topology detector."""
    global _detector
    if _detector is None:
        _detector = TopologyDetector()
    return _detector


def detect_topology(partition: str = "") -> HardwareTopology:
    """Convenience function to detect topology."""
    return get_detector().detect(partition)


