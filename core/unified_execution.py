def generate_node_sequence(max_nodes: int, min_nodes: int = 1) -> List[int]:
    """
    Generate node sequence using powers of 2.
    
    FIXES: Removes hardcoded sequences like [1, 2, 4].
    Dynamically generates based on max_nodes.
    
    Args:
        max_nodes: Maximum number of nodes
        min_nodes: Minimum number of nodes (default 1)
        
    Returns:
        List of node counts (powers of 2 up to max_nodes)
    """
    sequence = []
    n = min_nodes
    
    # Generate powers of 2
    while n <= max_nodes:
        sequence.append(n)
        n *= 2
    
    # Include max_nodes if not a power of 2
    if sequence[-1] != max_nodes:
        sequence.append(max_nodes)
    
    return sequence


