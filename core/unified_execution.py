@dataclass
class HardwareTopology:
    """
    Hardware topology for a compute node.
    
    All values are detected at runtime, not hardcoded.
    This is the SINGLE SOURCE OF TRUTH for hardware info.
    """
    partition: str
    cpu_cores_per_node: int
    gpus_per_node: int = 0
    gpu_vendor: GPUVendor = GPUVendor.NONE
    memory_per_node_gb: int = 0
    detection_method: str = "unknown"
    
    # Derived values (computed in __post_init__)
    mpi_ranks_per_node: int = field(init=False)
    cores_per_rank: int = field(init=False)
    is_gpu_partition: bool = field(init=False)
    
    def __post_init__(self):
        """
        Compute derived values.
        
        CRITICAL FORMULAS:
        - GPU jobs: ranks_per_node = gpus_per_node (1 rank per GPU)
        - GPU jobs: cores_per_rank = cpus / gpus
        - CPU jobs: ranks_per_node = cpus (1 rank per core)
        - CPU jobs: cores_per_rank = 1
        """
        self.is_gpu_partition = self.gpus_per_node > 0
        
        if self.is_gpu_partition:
            # GPU job: 1 MPI rank per GPU
            self.mpi_ranks_per_node = self.gpus_per_node
            self.cores_per_rank = self.cpu_cores_per_node // self.gpus_per_node
        else:
            # CPU-only job: 1 MPI rank per core
            self.mpi_ranks_per_node = self.cpu_cores_per_node
            self.cores_per_rank = 1
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary."""
        return {
            'partition': self.partition,
            'cpu_cores_per_node': self.cpu_cores_per_node,
            'gpus_per_node': self.gpus_per_node,
            'gpu_vendor': self.gpu_vendor.value,
            'mpi_ranks_per_node': self.mpi_ranks_per_node,
            'cores_per_rank': self.cores_per_rank,
            'is_gpu_partition': self.is_gpu_partition,
            'detection_method': self.detection_method,
        }


@dataclass
class MPIConfiguration:
    """
    MPI configuration for a scaling run.
    
    Derived from topology - no hardcoded values.
    """
    num_nodes: int
    topology: HardwareTopology
    
    # Derived values
    total_mpi_ranks: int = field(init=False)
    mpi_ranks_per_node: int = field(init=False)
    cores_per_rank: int = field(init=False)
    total_gpus: int = field(init=False)
    
    def __post_init__(self):
        """Compute MPI configuration from topology."""
        self.mpi_ranks_per_node = self.topology.mpi_ranks_per_node
        self.cores_per_rank = self.topology.cores_per_rank
        self.total_mpi_ranks = self.num_nodes * self.mpi_ranks_per_node
        self.total_gpus = self.num_nodes * self.topology.gpus_per_node
    
    def get_mpirun_args(self) -> List[str]:
        """
        Generate mpirun arguments.
        
        Returns:
            List of mpirun arguments (not including 'mpirun' itself)
        """
        return [
            '-np', str(self.total_mpi_ranks),
            '--map-by', f'ppr:{self.mpi_ranks_per_node}:node:PE={self.cores_per_rank}',
            '--report-bindings',
        ]
    
    def get_mpirun_command_string(self) -> str:
        """Get complete mpirun command as string (without executable)."""
        args = ['mpirun'] + self.get_mpirun_args()
        return ' '.join(args)


@dataclass
class SlurmConfiguration:
    """
    SLURM job configuration.
    
    CRITICAL: --ntasks-per-node uses FULL CPU count, not MPI ranks.
    This is required for proper CPU affinity with mpirun mapping.
    """
    job_name: str
    num_nodes: int
    partition: str
    topology: HardwareTopology
    time_limit: str = "02:00:00"
    account: str = ""
    qos: str = ""
    exclusive: bool = True
    
    def get_directives(self) -> List[str]:
        """
        Generate SLURM directives.
        
        CRITICAL FIX: --ntasks-per-node = FULL CPU count, not MPI ranks
        """
        directives = [
            f"#SBATCH --job-name={self.job_name}",
            f"#SBATCH --nodes={self.num_nodes}",
            # CRITICAL: Use FULL CPU count for proper affinity
            f"#SBATCH --ntasks-per-node={self.topology.cpu_cores_per_node}",
            f"#SBATCH --time={self.time_limit}",
            f"#SBATCH --partition={self.partition}",
        ]
        
        # Add GPU directive only if GPUs present
        if self.topology.gpus_per_node > 0:
            directives.append(f"#SBATCH --gres=gpu:{self.topology.gpus_per_node}")
        
        if self.account:
            directives.append(f"#SBATCH --account={self.account}")
        
        if self.qos:
            directives.append(f"#SBATCH --qos={self.qos}")
        
        if self.exclusive:
            directives.append("#SBATCH --exclusive")
        
        return directives


