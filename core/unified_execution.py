class IncrementalResultWriter:
    """
    Write scaling results incrementally.
    
    Results are written immediately after each run, not batched at the end.
    This allows real-time analysis and prevents data loss.
    
    Output structure:
        run_data/
        ├── weak_scaling_report_node1.json
        ├── weak_scaling_report_node2.json
        ├── weak_scaling_report_node4.json
        ├── summary.json
        ├── scaling_report.json
        └── scaling_report.csv
    """
    
    def __init__(
        self,
        output_dir: Path,
        scaling_type: str,
        partition: str = "",
        test_name: str = "scaling_test"
    ):
        self.output_dir = Path(output_dir)
        self.scaling_type = scaling_type.lower()
        self.partition = partition
        self.test_name = test_name
        
        # Create run_data directory
        self.data_dir = self.output_dir / "run_data"
        self.data_dir.mkdir(parents=True, exist_ok=True)
        
        # Track results
        self._results: Dict[int, RunResult] = {}
        self._baseline_time: Optional[float] = None
        self._start_time = datetime.now().isoformat()
        
        logger.info(f"Initialized result writer: {self.data_dir}")
    
    def write_run_result(self, result: RunResult) -> Path:
        """
        Write a single run's result IMMEDIATELY.
        
        Args:
            result: RunResult from completed run
            
        Returns:
            Path to the written JSON file
        """
        # Compute metrics
        self._compute_metrics(result)
        
        # Generate filename
        filename = f"{self.scaling_type}_scaling_report_node{result.node_count}.json"
        filepath = self.data_dir / filename
        
        # Write JSON
        data = result.to_dict()
        data['timestamp'] = datetime.now().isoformat()
        
        with open(filepath, 'w') as f:
            json.dump(data, f, indent=2)
        
        logger.info(f"✓ Wrote result: {filepath}")
        
        # Store for summary
        self._results[result.node_count] = result
        
        # Update baseline
        if result.node_count == 1 and result.status == "completed":
            self._baseline_time = result.wall_time_seconds
        
        return filepath
    
    def create_pending_result(
        self,
        node_count: int,
        mpi_config: MPIConfiguration,
        topology: HardwareTopology,
        job_directory: str = "",
        slurm_job_id: str = ""
    ) -> RunResult:
        """Create and write a pending result before the run starts."""
        result = RunResult(
            run_id=f"{self.scaling_type}_node{node_count}",
            scaling_type=self.scaling_type,
            node_count=node_count,
            start_time=datetime.now().isoformat(),
            total_mpi_ranks=mpi_config.total_mpi_ranks,
            mpi_ranks_per_node=mpi_config.mpi_ranks_per_node,
            cores_per_rank=mpi_config.cores_per_rank,
            gpus_per_node=topology.gpus_per_node,
            total_gpus=mpi_config.total_gpus,
            status="pending",
            job_directory=job_directory,
            slurm_job_id=slurm_job_id,
        )
        
        self.write_run_result(result)
        return result
    
    def update_run_status(
        self,
        node_count: int,
        status: str,
        wall_time: float = 0.0,
        exit_code: int = 0,
        error_message: str = ""
    ) -> None:
        """Update status of an existing run."""
        if node_count not in self._results:
            logger.warning(f"No result for node count {node_count}")
            return
        
        result = self._results[node_count]
        result.status = status
        result.wall_time_seconds = wall_time
        result.exit_code = exit_code
        result.error_message = error_message
        
        if status == "completed":
            result.end_time = datetime.now().isoformat()
        
        self.write_run_result(result)
    
    def _compute_metrics(self, result: RunResult) -> None:
        """Compute speedup and efficiency."""
        if self._baseline_time is None or self._baseline_time <= 0:
            return
        
        if result.wall_time_seconds <= 0:
            return
        
        if self.scaling_type == "strong":
            result.speedup = self._baseline_time / result.wall_time_seconds
            result.efficiency = result.speedup / result.node_count * 100
        else:
            result.efficiency = (self._baseline_time / result.wall_time_seconds) * 100
            result.speedup = result.node_count
    
    def write_summary(self) -> Path:
        """Write summary.json after all runs."""
        sorted_results = sorted(self._results.values(), key=lambda r: r.node_count)
        
        summary = {
            'test_name': self.test_name,
            'scaling_type': self.scaling_type,
            'partition': self.partition,
            'start_time': self._start_time,
            'end_time': datetime.now().isoformat(),
            'total_runs': len(self._results),
            'completed_runs': sum(1 for r in self._results.values() if r.status == "completed"),
            'failed_runs': sum(1 for r in self._results.values() if r.status == "failed"),
            'node_sequence': sorted(self._results.keys()),
            'baseline_time': self._baseline_time or 0,
            'results': [r.to_dict() for r in sorted_results],
        }
        
        filepath = self.data_dir / "summary.json"
        with open(filepath, 'w') as f:
            json.dump(summary, f, indent=2)
        
        logger.info(f"✓ Wrote summary: {filepath}")
        return filepath
    
    def write_csv_report(self) -> Path:
        """Write CSV report for easy post-processing."""
        sorted_results = sorted(self._results.values(), key=lambda r: r.node_count)
        
        lines = [
            "nodes,gpus_per_node,total_gpus,mpi_ranks,wall_time_s,speedup,efficiency_pct,status,timestamp"
        ]
        
        for r in sorted_results:
            lines.append(
                f"{r.node_count},{r.gpus_per_node},{r.total_gpus},"
                f"{r.total_mpi_ranks},{r.wall_time_seconds:.2f},"
                f"{r.speedup:.2f},{r.efficiency:.1f},{r.status},{r.end_time}"
            )
        
        filepath = self.data_dir / "scaling_report.csv"
        with open(filepath, 'w') as f:
            f.write('\n'.join(lines))
        
        logger.info(f"✓ Wrote CSV: {filepath}")
        return filepath
    
    def write_aggregated_report(self) -> Path:
        """Write aggregated JSON report."""
        sorted_results = sorted(self._results.values(), key=lambda r: r.node_count)
        
        report = {
            'test_name': self.test_name,
            'scaling_type': self.scaling_type,
            'partition': self.partition,
            'generated_at': datetime.now().isoformat(),
            'baseline': {
                'nodes': 1,
                'time_seconds': self._baseline_time or 0
            },
            'results': [
                {
                    'nodes': r.node_count,
                    'gpus_per_node': r.gpus_per_node,
                    'total_gpus': r.total_gpus,
                    'total_ranks': r.total_mpi_ranks,
                    'time_seconds': r.wall_time_seconds,
                    'speedup': r.speedup,
                    'efficiency': r.efficiency,
                    'status': r.status,
                }
                for r in sorted_results
            ]
        }
        
        filepath = self.data_dir / "scaling_report.json"
        with open(filepath, 'w') as f:
            json.dump(report, f, indent=2)
        
        logger.info(f"✓ Wrote aggregated report: {filepath}")
        return filepath
    
    def get_result(self, node_count: int) -> Optional[RunResult]:
        """Get result for a specific node count."""
        return self._results.get(node_count)


