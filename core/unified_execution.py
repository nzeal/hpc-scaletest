def generate_gpu_binding_script(output_dir: Path) -> Path:
    """
    Generate the GPU binding script.
    
    The script uses OMPI_COMM_WORLD_LOCAL_RANK to set CUDA_VISIBLE_DEVICES,
    ensuring each MPI rank gets a unique GPU.
    
    Args:
        output_dir: Directory to write bind.sh
        
    Returns:
        Path to generated bind.sh
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    bind_path = output_dir / "bind.sh"
    with open(bind_path, 'w') as f:
        f.write(GPU_BIND_SCRIPT)
    
    os.chmod(bind_path, 0o755)
    
    logger.debug(f"Generated GPU binding script: {bind_path}")
    return bind_path


def get_gpu_binding_script_content() -> str:
    """Get the GPU binding script content."""
    return GPU_BIND_SCRIPT


