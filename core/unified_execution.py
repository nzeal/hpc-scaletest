def generate_job_script(
    slurm_config: SlurmConfiguration,
    mpi_config: MPIConfiguration,
    binary_dir: str,
    executable: str,
    args: List[str] = None,
    modules: List[str] = None,
    working_dir: str = ".",
) -> str:
    """
    Generate a complete SLURM job script.
    
    CRITICAL FIXES:
    1. BINARY points to absolute build directory (not ${PWD})
    2. Executable is the actual binary (not bind.sh)
    3. bind.sh is generated inline and wraps the executable
    4. mpirun uses ppr:R:node:PE=C mapping
    5. SLURM uses full CPU count for --ntasks-per-node
    
    Args:
        slurm_config: SLURM configuration
        mpi_config: MPI configuration
        binary_dir: Absolute path to build directory
        executable: Name of the executable
        args: Arguments for executable
        modules: Module load commands
        working_dir: Working directory for job
        
    Returns:
        Complete job script as string
    """
    args = args or []
    modules = modules or []
    topology = slurm_config.topology
    
    # Build script
    lines = [
        "#!/bin/bash",
        "# " + "=" * 75,
        "# SLURM Job Script - Generated by HPC-ScaleTest",
        "# " + "=" * 75,
        f"# Partition: {slurm_config.partition}",
        f"# Nodes: {slurm_config.num_nodes}",
        f"# CPUs per node: {topology.cpu_cores_per_node}",
        f"# GPUs per node: {topology.gpus_per_node}",
        f"#",
        f"# MPI Configuration:",
        f"#   Total ranks: {mpi_config.total_mpi_ranks}",
        f"#   Ranks per node: {mpi_config.mpi_ranks_per_node}",
        f"#   Cores per rank: {mpi_config.cores_per_rank}",
        "# " + "=" * 75,
        "",
    ]
    
    # SLURM directives
    lines.extend(slurm_config.get_directives())
    lines.append(f"#SBATCH --output={working_dir}/job_%j.out")
    lines.append(f"#SBATCH --error={working_dir}/job_%j.err")
    lines.append("")
    
    # Environment setup
    lines.append("# " + "-" * 75)
    lines.append("# Environment Setup")
    lines.append("# " + "-" * 75)
    for mod in modules:
        lines.append(mod)
    lines.append("")
    
    # Binary location - CRITICAL: use absolute path
    lines.append("# CRITICAL: BINARY must be absolute path to build directory")
    lines.append(f"export BINARY={binary_dir}")
    lines.append("")
    
    # Job info
    lines.append("echo \"" + "=" * 60 + "\"")
    lines.append('echo "Job ID: $SLURM_JOB_ID"')
    lines.append('echo "Nodes: $SLURM_NNODES"')
    lines.append(f'echo "CPUs per node: {topology.cpu_cores_per_node}"')
    lines.append(f'echo "GPUs per node: {topology.gpus_per_node}"')
    lines.append(f'echo "MPI ranks per node: {mpi_config.mpi_ranks_per_node}"')
    lines.append(f'echo "Cores per rank: {mpi_config.cores_per_rank}"')
    lines.append('echo "BINARY: $BINARY"')
    lines.append("echo \"" + "=" * 60 + "\"")
    lines.append("")
    
    lines.append(f"cd {working_dir}")
    lines.append(f"export OMP_NUM_THREADS={mpi_config.cores_per_rank}")
    lines.append("")
    
    # GPU binding script - only for GPU jobs
    if topology.gpus_per_node > 0:
        lines.append("# " + "-" * 75)
        lines.append("# GPU Binding Script")
        lines.append("# Uses OMPI_COMM_WORLD_LOCAL_RANK to bind each rank to a unique GPU")
        lines.append("# " + "-" * 75)
        lines.append("cat > bind.sh << 'BIND_EOF'")
        lines.append(GPU_BIND_SCRIPT.strip())
        lines.append("BIND_EOF")
        lines.append("chmod +x bind.sh")
        lines.append("")
    
    # Build mpirun command
    mpi_cmd_parts = ['mpirun'] + mpi_config.get_mpirun_args()
    
    # Add GPU binding wrapper if needed
    if topology.gpus_per_node > 0:
        mpi_cmd_parts.append('./bind.sh')
    
    # Add executable
    mpi_cmd_parts.append(f'$BINARY/{executable}')
    
    # Add arguments
    mpi_cmd_parts.extend(args)
    
    mpi_cmd = ' '.join(mpi_cmd_parts)
    
    # Execute with timing
    lines.append("# " + "-" * 75)
    lines.append("# Execute Application")
    lines.append("# " + "-" * 75)
    lines.append('echo ""')
    lines.append('echo "Starting: $(date)"')
    lines.append(f'echo "Command: {mpi_cmd}"')
    lines.append('echo ""')
    lines.append("")
    lines.append('start_time=$(date +%s.%N)')
    lines.append("")
    lines.append(mpi_cmd)
    lines.append("")
    lines.append('exit_code=$?')
    lines.append('end_time=$(date +%s.%N)')
    lines.append('elapsed=$(echo "$end_time - $start_time" | bc)')
    lines.append("")
    lines.append("echo \"" + "=" * 60 + "\"")
    lines.append('echo "Completed: $(date)"')
    lines.append('echo "Exit code: $exit_code"')
    lines.append('echo "Elapsed: $elapsed seconds"')
    lines.append("echo \"" + "=" * 60 + "\"")
    lines.append("")
    
    # Write timing JSON
    lines.append("# Write timing JSON for result parsing")
    lines.append('cat > timing.json << EOF')
    lines.append('{')
    lines.append('  "wall_time": $elapsed,')
    lines.append('  "exit_code": $exit_code,')
    lines.append('  "start_time": "$start_time",')
    lines.append('  "end_time": "$end_time"')
    lines.append('}')
    lines.append('EOF')
    lines.append("")
    lines.append('exit $exit_code')
    
    return '\n'.join(lines)


