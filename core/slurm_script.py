#!/usr/bin/env python3
"""
core/slurm_script.py - SLURM Job Script Generator

This module generates SLURM job scripts with correct resource allocation.

CRITICAL DISTINCTION:
=====================
There are TWO different resource specifications:

1. SLURM Resource Allocation (full node):
   - `#SBATCH --ntasks-per-node=32` - Request all CPUs on node
   - `#SBATCH --gres=gpu:4` - Request all GPUs on node
   - This ensures exclusive node access and proper accounting

2. MPI Execution (actual tasks):
   - `mpirun -np 16 --map-by ppr:4:node:PE=8` - Run 4 MPI ranks per node
   - Each rank gets 8 CPU cores via PE=8
   - This is the actual parallel execution configuration

For Leonardo Booster (32 cores, 4 GPUs per node):
- SLURM allocates: 32 CPUs, 4 GPUs per node (full node)
- MPI runs: 4 ranks per node, 8 cores each (actual execution)

Author: HPC-ScaleTest Contributors
"""

